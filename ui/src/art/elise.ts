/* Elise, the R&D mascot: a 32px pixel-art physicist after Lise Meitner, brown hair
   in a bun, in a professor's jacket and long skirt. Drawn side on, facing right;
   EliseScene mirrors her to face left.

   Every frame is a list of rows, one character per pixel ("." is clear), coloured
   by ELISE_PAL. An activity frame is the whole station: Elise and her props
   together, so the props can sit in front of her (the armchair's arm). `eliseX` is
   where Elise's own 32px frame starts inside it, so she can step from the walk
   straight into the activity without a jump, and `emit` is where the activity's
   maths symbols rise from. `order` plays the frames, `ms` per step. */

export const ELISE_PX = 32;

export type EliseClip = {
  /** width of every frame, in pixels; all are 32 tall */
  w: number;
  eliseX: number;
  ms: number;
  order: readonly number[];
  frames: readonly (readonly string[])[];
  emit?: readonly [number, number];
  /** the props alone, for the station she is away from */
  empty?: readonly string[];
};

